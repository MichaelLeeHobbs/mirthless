// Usage: node docs/research/voice-of-user/gen-tables.mjs docs/research/voice-of-user/data > docs/research/voice-of-user/ranking.md
// Writes the full ranking that doc 18 links to. Edit clusters.mjs (status, call, notes), then rerun.
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { AREAS } from './clusters.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const dir = process.argv[2];
const scored = JSON.parse(execFileSync('node', [join(here, 'score.mjs'), dir, '--json'], { encoding: 'utf8', maxBuffer: 1 << 24 }));
scored.forEach((s, i) => { s.rank = i + 1; });

const STATUS = { have: 'Have', partial: 'Partial', gap: 'Missing', 'n/a': 'n/a' };
const esc = (t) => String(t).replace(/\|/g, '\\|');
const links = (s) => s.evidence.filter((e) => e.url).slice(0, 2).map((e, i) => `[${i + 1}](${e.url})`).join(' ');
const streams = (s) => s.streams.join(' ');

const table = (rows, cols) => {
  const head = `| ${cols.map((c) => c[0]).join(' | ')} |\n|${cols.map(() => '---').join('|')}|`;
  return [head, ...rows.map((r) => `| ${cols.map((c) => c[1](r)).join(' | ')} |`)].join('\n');
};

const base = [
  ['Rank', (s) => s.rank],
  ['ID', (s) => s.id],
  ['Theme', (s) => esc(s.title)],
  ['Score', (s) => s.score],
];

const total = scored.reduce((n, s) => n + s.entries.length, 0);
console.log('# Voice of the user: full ranking\n');
console.log(`Generated by \`gen-tables.mjs\` from ${total} entries in \`data/\`, grouped into ${scored.length} themes by \`clusters.mjs\`. Do not edit by hand: change \`clusters.mjs\` and rerun. The analysis and recommended order are in [doc 18](../../design/18-voice-of-the-user.md).\n`);
console.log('Rank is by demand score only. Call: build, have (already ours), consider, partner (integrate rather than build), wont, context (not a feature).\n');

console.log('## Build\n');
console.log(table(scored.filter((s) => s.verdict === 'build'), [...base, ['Status', (s) => STATUS[s.status]], ['Note', (s) => esc(s.note)]]));

console.log('\n## Already ours\n');
console.log(table(scored.filter((s) => s.verdict === 'have'), [...base, ['Note', (s) => esc(s.note)]]));

console.log('\n## Consider or partner\n');
console.log(table(scored.filter((s) => s.verdict === 'consider' || s.verdict === 'partner'), [...base, ['Call', (s) => s.verdict], ['Note', (s) => esc(s.note)]]));

console.log("\n## Won't do, and context\n");
console.log(table(scored.filter((s) => s.verdict === 'wont' || s.verdict === 'context'), [...base, ['Call', (s) => s.verdict], ['Why', (s) => esc(s.note)]]));

console.log('\n## By area, with evidence\n');
console.log('Found by: MG Mirth GitHub, OB OIE/BridgeLink, QA Stack Overflow and forums, CR commercial reviews, SB Reddit/HN/blogs, WP workaround tools and paid add-ons, OS open-source engines.');
for (const [code, name] of Object.entries(AREAS)) {
  const rows = scored.filter((s) => s.area === code);
  if (!rows.length) continue;
  console.log(`\n### ${name}\n`);
  console.log(table(rows, [
    ['Rank', (s) => s.rank], ['ID', (s) => s.id], ['Theme', (s) => esc(s.title)], ['Score', (s) => s.score],
    ['Sources', (s) => s.sources], ['Votes/stars', (s) => s.reactions], ['Found by', streams],
    ['Status', (s) => STATUS[s.status]], ['Call', (s) => s.verdict], ['Evidence', links],
  ]));
}
